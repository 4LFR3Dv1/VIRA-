export function txlineCapabilities() {
  const byFamily = txlineEndpointCatalog.reduce((accumulator, endpoint) => {
    accumulator[endpoint.family] = accumulator[endpoint.family] ?? [];
    accumulator[endpoint.family].push(endpoint);
    return accumulator;
  }, {});

  return {
    provider: "TxLINE",
    source: "https://txline-docs.txodds.com/llms-full.txt",
    generatedAt: new Date().toISOString(),
    endpoints: txlineEndpointCatalog,
    byFamily,
    unsupported: unsupportedTxlineData,
  };
}
